"""Generate the site's diagrams that embed their fonts and colours.

Sources live next to this script. The architecture diagram of
docs/internals/ARCHITECTURE.md:

- architecture.svg: the diagram source. ``/* {{FONTS}} */`` marks where the
  site's fonts are embedded, so the image renders the same on GitHub and the
  site, which both show it as a plain image. It is written twice, light and
  dark, because an image cannot follow the page's theme.

And the README copies of the home page's three Features diagrams:

- feature-*.svg: the diagram sources, colour-free. The home page inlines them
  (pymdownx.snippets) and styles them with docs/stylesheets/features.css. The
  README can only show images, so each gets one standalone copy per site
  theme, with that theme's token values, features.css, and the fonts embedded.

Run from anywhere after editing a source, then commit the outputs:

    python3 website/illustration/build.py

Outputs: docs/user/assets/architecture.svg with its architecture-dark.svg twin,
and docs/user/assets/feature-*-{light,dark}.svg (published at
booley.dev/docs/assets/, where the README links them).
"""

import base64
import re
from pathlib import Path
from typing import NamedTuple

HERE = Path(__file__).resolve().parent
WEBSITE = HERE.parent
ARCHITECTURE_OUT = WEBSITE.parent / "docs" / "user" / "assets" / "architecture.svg"
ARCHITECTURE_DARK_OUT = ARCHITECTURE_OUT.with_name("architecture-dark.svg")
# The dark copy's colour tokens: the site's dark datasheet palette (datasheet.css).
ARCHITECTURE_DARK_TOKENS = {
    "paper": "#121619",
    "ink": "#e4e8eb",
    "ink-2": "#a7b0b9",
    "rule": "#5d6873",
    "fill": "#1e2429",
    "fill-2": "#181d21",
    "mask": "#4fbf93",
}
FONTS = WEBSITE / "docs" / "assets" / "fonts"


class FontFace(NamedTuple):
    """One self-hosted font file and the @font-face ranges it covers."""

    family: str
    weight: str
    stretch: str
    file: str


ARCHIVO = FontFace("Archivo", "100 900", "62% 125%", "archivo-latin-standard-normal.woff2")
# The faces the architecture diagram uses.
ARCHITECTURE_FONTS = (
    ARCHIVO,
    FontFace("JetBrains Mono", "600", "100%", "jetbrains-mono-latin-600-normal.woff2"),
)
# The faces the Features diagrams use: Archivo, and JetBrains Mono at its regular weight.
FEATURE_FONTS = (
    ARCHIVO,
    FontFace("JetBrains Mono", "400", "100%", "jetbrains-mono-latin-400-normal.woff2"),
)
FONTS_MARKER = "/* {{FONTS}} */"
GENERATED = "Generated by website/illustration/build.py; edit the sources there, not this file."


def font_faces(fonts: tuple[FontFace, ...]) -> str:
    """Return @font-face rules embedding each font file as a data URI."""
    return "\n".join(
        f'    @font-face {{ font-family: "{face.family}"; font-style: normal;'
        f" font-weight: {face.weight}; font-stretch: {face.stretch};"
        " src: url(data:font/woff2;base64,"
        f'{base64.b64encode((FONTS / face.file).read_bytes()).decode("ascii")}) format("woff2"); }}'
        for face in fonts
    )


def architecture_svg(*, dark: bool = False) -> str:
    """Return the architecture diagram with its fonts embedded as data URIs.

    ``dark`` swaps each colour token for its ARCHITECTURE_DARK_TOKENS value. An image
    cannot see the page's theme toggle, so the page shows one copy per theme.
    """
    source = (HERE / "architecture.svg").read_text(encoding="utf-8")
    if source.count(FONTS_MARKER) != 1:
        raise ValueError(f"architecture.svg must contain {FONTS_MARKER} exactly once")
    if dark:
        for token, colour in ARCHITECTURE_DARK_TOKENS.items():
            source, count = re.subn(
                rf"(--{re.escape(token)}: )#[0-9a-fA-F]{{6}}", rf"\g<1>{colour}", source
            )
            if count != 1:
                raise ValueError(f"architecture.svg must define --{token} exactly once")
    notice = f"<!-- {GENERATED} Fonts: SIL OFL 1.1, see website/docs/assets/fonts/. -->\n"
    return notice + source.replace(f"    {FONTS_MARKER}", font_faces(ARCHITECTURE_FONTS))


# ---------------------------------------------------------------- Features diagrams
FEATURE_DIAGRAMS = ("feature-tools", "feature-parallel", "feature-results")
FEATURES_CSS = WEBSITE / "docs" / "stylesheets" / "features.css"
TOKENS_CSS = WEBSITE / "docs" / "stylesheets" / "datasheet.css"
FEATURES_OUT = ARCHITECTURE_OUT.parent
# The token rules each theme applies, in cascade order: dark overrides light.
THEME_RULES = {"light": (":root",), "dark": (":root", ':root[data-theme="dark"]')}
# README image size per viewBox unit. The home page draws the 440-unit diagrams
# in a column of about 504px (1.15); the README column is wider, so a little more.
README_SCALE = 1.2
_SVG_OPEN = re.compile(r'<svg ([^>]*?)viewBox="0 0 (\d+) (\d+)"([^>]*)>')


def feature_out(name: str, theme: str) -> Path:
    """Return the path of one theme's README copy of a Features diagram."""
    return FEATURES_OUT / f"{name}-{theme}.svg"


def theme_tokens(theme: str) -> str:
    """Return one theme's datasheet.css custom properties as CSS declarations."""
    css = re.sub(r"/\*.*?\*/", "", TOKENS_CSS.read_text(encoding="utf-8"), flags=re.S)
    tokens: dict[str, str] = {}
    for selector in THEME_RULES[theme]:
        rule = re.search(re.escape(selector) + r"\s*\{([^}]*)\}", css)
        if rule is None:
            raise ValueError(f"datasheet.css has no {selector} token rule")
        tokens.update(re.findall(r"(--[\w-]+)\s*:\s*([^;]+?)\s*;", rule.group(1)))
    return " ".join(f"{name}: {value};" for name, value in tokens.items())


def feature_svg(name: str, theme: str) -> str:
    """Return a standalone Features diagram: one theme's colours, features.css, and fonts."""
    source = (HERE / f"{name}.svg").read_text(encoding="utf-8")
    opening = _SVG_OPEN.match(source)
    if opening is None:
        raise ValueError(f"{name}.svg must open with an <svg> whose viewBox starts at 0 0")
    before, width, height, after = opening.groups()
    size = (
        f'width="{round(int(width) * README_SCALE)}" height="{round(int(height) * README_SCALE)}"'
    )
    style = (
        "<style>\n"
        f"{font_faces(FEATURE_FONTS)}\n"
        f"    .fd {{ {theme_tokens(theme)} }}\n"
        f"{FEATURES_CSS.read_text(encoding='utf-8')}"
        "</style>\n"
    )
    notice = (
        f"<!-- {GENERATED} Source: website/illustration/{name}.svg, {theme} theme."
        " Fonts: SIL OFL 1.1, see website/docs/assets/fonts/. -->\n"
    )
    svg_open = f'<svg {before}viewBox="0 0 {width} {height}" {size}{after}>\n'
    return notice + svg_open + style + source[opening.end() :].lstrip("\n")


def main() -> None:
    ARCHITECTURE_OUT.write_text(architecture_svg(), encoding="utf-8")
    ARCHITECTURE_DARK_OUT.write_text(architecture_svg(dark=True), encoding="utf-8")
    for name in FEATURE_DIAGRAMS:
        for theme in THEME_RULES:
            feature_out(name, theme).write_text(feature_svg(name, theme), encoding="utf-8")


if __name__ == "__main__":
    main()
