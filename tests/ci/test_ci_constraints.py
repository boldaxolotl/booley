"""The committed CI constraints file stays current and wired in (#2707)."""

from __future__ import annotations

import re
import sys
import tomllib
from pathlib import Path
from types import ModuleType

import pytest
import yaml

_ROOT = Path(__file__).parents[2]
sys.path.insert(0, str(_ROOT / ".github/scripts"))

_CONSTRAINTS = _ROOT / ".github/ci/constraints.txt"
_PIN = re.compile(r"^(?P<name>[A-Za-z0-9][A-Za-z0-9._-]*)==(?P<version>[^\s;#]+)", re.MULTILINE)


def _checker() -> ModuleType:
    """Import the checker inside the test body, so a missing module fails the test itself."""
    import ci_constraints

    return ci_constraints


def _project() -> dict:
    return tomllib.loads((_ROOT / "pyproject.toml").read_text(encoding="utf-8"))["project"]


def _pins(path: Path) -> dict[str, set[str]]:
    """Map each normalized package name in a requirements-style file to its pinned versions."""
    pins: dict[str, set[str]] = {}
    for match in _PIN.finditer(path.read_text(encoding="utf-8")):
        name = match["name"].lower().replace("_", "-")
        pins.setdefault(name, set()).add(match["version"])
    return pins


def test_constraints_file_is_current() -> None:
    """AC2/AC3/AC5: one universal unhashed file pins every direct requirement of pyproject."""
    checker = _checker()
    project = _project()
    reasons = checker.stale_reasons(project, _CONSTRAINTS.read_text(encoding="utf-8"))
    assert reasons == [], checker.failure_message(reasons, checker.regenerate_command(project))


_MINIMAL_PROJECT = {
    "requires-python": ">=3.11",
    "dependencies": ["alpha>=1.0", "beta==2.0"],
    "optional-dependencies": {"test": ["gamma>=3"]},
}


def _minimal_constraints() -> str:
    """Write the file uv would compile for ``_MINIMAL_PROJECT``."""
    direct = {"alpha": "1.2", "beta": "2.0", "gamma": "3.1"}
    lines = [
        "# This file was autogenerated by uv via the following command:",
        "#    uv pip compile pyproject.toml --all-extras --universal --python-version 3.11"
        " -o .github/ci/constraints.txt",
    ]
    for name, version in direct.items():
        lines += [f"{name}=={version}", "    # via booley-rtl (pyproject.toml)"]
    return "\n".join(lines) + "\n"


_STALE_CASES = {
    "added-dependency": (
        _MINIMAL_PROJECT | {"dependencies": ["alpha>=1.0", "beta==2.0", "delta>=1"]},
        "delta>=1 has no pin",
    ),
    "bumped-exact-pin": (
        _MINIMAL_PROJECT | {"dependencies": ["alpha>=1.0", "beta==2.1"]},
        "beta==2.1 does not admit pinned 2.0",
    ),
    "removed-dependency": (
        _MINIMAL_PROJECT | {"dependencies": ["alpha>=1.0"]},
        "direct dependency names differ from pyproject: beta",
    ),
    "raised-requires-python": (
        _MINIMAL_PROJECT | {"requires-python": ">=3.12"},
        "--python-version 3.12",
    ),
}


def test_stale_constraints_name_the_regenerate_command(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    """AC3: each kind of staleness exits 1 and prints its reason plus the regenerate command."""
    checker = _checker()
    (tmp_path / ".github/ci").mkdir(parents=True)
    (tmp_path / ".github/ci/constraints.txt").write_text(_minimal_constraints(), encoding="utf-8")
    for case, (project, reason) in _STALE_CASES.items():
        body = ["[project]", 'name = "x"', f'requires-python = "{project["requires-python"]}"']
        body.append("dependencies = " + repr(project["dependencies"]).replace("'", '"'))
        body.append("[project.optional-dependencies]")
        body.append("test = " + repr(project["optional-dependencies"]["test"]).replace("'", '"'))
        (tmp_path / "pyproject.toml").write_text("\n".join(body) + "\n", encoding="utf-8")

        assert checker.main(tmp_path) == 1, case

        stderr = capsys.readouterr().err
        assert reason in stderr, case
        assert f"Regenerate with: {checker.regenerate_command(project)}" in stderr, case


def test_release_semantic_checks_constraints_before_any_project_install() -> None:
    """AC3: the always-run job fails stale files before pip could report ResolutionImpossible."""
    workflow = yaml.safe_load((_ROOT / ".github/workflows/test.yml").read_text(encoding="utf-8"))
    runs = [step["run"] for step in workflow["jobs"]["release-semantic"]["steps"] if "run" in step]
    assert any(run.strip() == "python .github/scripts/ci_constraints.py" for run in runs)
    assert not any(".[" in run or "-e ." in run for run in runs)


def test_readiness_runners_and_ci_requirements_match_constraints() -> None:
    """AC5: readiness runner pins and CI requirement files agree with the constraints file."""
    from booley.dev_support.agent_readiness import runner_pins

    constrained = _pins(_CONSTRAINTS)
    for name, version in runner_pins(_ROOT).items():
        assert constrained.get(name) == {version}, f"readiness pin {name}=={version} drifted"
    for path in sorted((_ROOT / ".github/ci").glob("requirements-*.txt")):
        for name, versions in _pins(path).items():
            # CI-only tools (twine, ...) are not project dependencies; only shared names compare.
            if name in constrained:
                assert constrained[name] == versions, f"{path.name}: {name} drifted"


def test_contributing_guide_documents_optional_constraints() -> None:
    """AC6: the plain editable install stays, and the optional constraints are documented."""
    checker = _checker()
    guide = (_ROOT / "docs/internals/CONTRIBUTING.md").read_text(encoding="utf-8")
    assert 'pip install -e ".[dev]"' in guide
    assert 'pip install -e ".[dev]" -c .github/ci/constraints.txt' in guide
    assert checker.regenerate_command(_project()) in guide
