# ---------------------------------------------------------------------------
# Vendored standalone import (SETUP-9): run as a script from a hooks dir that
# has no core/ package. The package-relative unit tests above never exercise
# the except-block import fallbacks, so drive them end-to-end as a subprocess.
# ---------------------------------------------------------------------------


def _vendor(dst: Path, *, include_runner: bool) -> None:
    """Copy the standalone hook files flat into *dst*, as init vendors them."""
    src = dev_support_dir()
    core = src.parent / "core"
    policy = src.parent / "commit_policy"
    dst.mkdir(parents=True, exist_ok=True)
    for name in ("validate_commit_msg.py", "commit_msg_utils.py"):
        shutil.copy2(src / name, dst / name)
    shutil.copy2(policy / "policy.py", dst / "booley_commit_policy.py")
    shutil.copy2(policy / "validation.py", dst / "booley_commit_validation.py")
    shutil.copy2(core / "boundary.py", dst / "boundary.py")
    if include_runner:
        shutil.copy2(core / "run_command.py", dst / "run_command.py")


def _run_vendored(dst: Path, msg: str, *, isolated: bool = False, staged: str = ""):
    """Run the vendored script on *msg* in a fresh configured repository at *dst*."""
    _init_repo(dst)
    if staged:
        _stage(dst, "note.txt", staged)
    argv = [sys.executable, str(dst / "validate_commit_msg.py"), msg]
    env = None
    if isolated:
        # No installed Booley and no checkout on PYTHONPATH (the conftest sets it):
        # only the vendored files beside the script can resolve imports.
        argv.insert(1, "-S")
        env = {k: v for k, v in os.environ.items() if k != "PYTHONPATH"}
    return run_bounded_child(argv, cwd=str(dst), env=env)


def test_vendored_flat_run_tool_resolves(tmp_path: Path) -> None:
    """init vendors run_command.py flat → imported by bare name, no crash."""
    _vendor(tmp_path, include_runner=True)
    proc = _run_vendored(tmp_path, "feat(x): ok")
    assert proc.returncode == 0, proc.stderr


def test_vendored_missing_runner_fails_loudly(tmp_path: Path) -> None:
    """A vendored dir without run_command.py has no fallback: the hook stops with an
    ImportError naming the modules it tried, not a silent half-working validation."""
    _vendor(tmp_path, include_runner=False)
    proc = _run_vendored(tmp_path, "feat(x): ok", isolated=True)
    assert proc.returncode != 0
    assert "cannot import run_command" in proc.stderr


def test_vendored_flat_run_tool_actually_scans_staged_diff(tmp_path: Path) -> None:
    """A Co-Authored-By trailer is a banned attribution term the diff scan flags: the
    resolved run_command must run ``git diff --cached``, not just import."""
    _vendor(tmp_path, include_runner=True)
    proc = _run_vendored(tmp_path, "feat(x): ok", staged="Co-Authored-By: somebody <x@y.z>\n")
    assert proc.returncode == 1, proc.stdout + proc.stderr
    assert "co-authored-by" in proc.stderr.lower()
