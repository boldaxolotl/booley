def _run_checked(argv: list[str]) -> None:
    """Run a fixture command under the shared bound; a failure shows its stderr."""
    result = run_bounded_child(argv)
    assert result.returncode == 0, result.stderr


def _write_project(root: Path, stealth: str = "enabled = true\n") -> Path:
    """Write ``root/.booley/booley.toml`` with a ``[stealth]`` section."""
    booley_dir = root / ".booley"
    booley_dir.mkdir(parents=True, exist_ok=True)
    (booley_dir / "booley.toml").write_bytes(f"[stealth]\n{stealth}".encode())
    return root


def _init_repo(root: Path, stealth: str | None = "enabled = true\n") -> Path:
    """Create a real Git repository at *root*, configured unless *stealth* is None."""
    root.mkdir(parents=True, exist_ok=True)
    _run_checked(["git", "init", "-q", str(root)])
    if stealth is not None:
        _write_project(root, stealth)
    return root


def _stage(repo: Path, name: str, content: str) -> None:
    """Stage a new file so ``git diff --cached`` sees *content* as added lines."""
    (repo / name).write_bytes(content.encode())
    _run_checked(["git", "-C", str(repo), "add", name])


def test_bundled_commit_msg_hook_honors_relocated_booley_dir(tmp_path: Path) -> None:
    """The installed hook reads ``[project].dir`` without importing Booley (``-S``)."""
    from booley.harness.setup.project_git_hook_bundle import build_project_git_hook_bundle

    repo = _init_repo(tmp_path / "repo", stealth=None)
    (repo / "booley.toml").write_bytes(b'[project]\ndir = "state"\n')
    (repo / "state").mkdir()
    (repo / "state" / "booley.toml").write_bytes(
        b"[stealth]\nenabled = true\nmax_body_lines = 0\n"
    )
    bundle = repo / "state" / ".managed" / "project-git-hooks.pyz"
    bundle.parent.mkdir()
    bundle.write_bytes(build_project_git_hook_bundle().content)
    message = tmp_path / "message.txt"
    message.write_bytes(b"Update ALU\n\nA body line over the cap.\n")

    result = run_bounded_child(
        [sys.executable, "-I", "-S", str(bundle), "commit-msg", str(message)], cwd=repo
    )

    assert result.returncode == 1, result.stderr
    assert "Commit message validation FAILED" in result.stderr


# ---------------------------------------------------------------------------
# validate_message over a real Project configuration
# ---------------------------------------------------------------------------

ON = "enabled = true\n"
CAP_ZERO = "enabled = true\nmax_body_lines = 0\n"
MERGE = "Merge branch 'feature'\n\n"


@pytest.mark.parametrize(
    ("stealth", "message", "error_fragment"),
    [
        # Booley enforces no subject convention or summary-length limit, and allows a body.
        (ON, "Update ALU\n", None),
        (ON, "x" * 200 + "\n", None),
        (ON, "", None),
        (ON, "Do thing\n\nBody text.\nSecond line.", None),
        (ON, "fix(a): do thing\n\n" + "\n".join(f"line {i}" for i in range(50)), None),
        # The banned list guards the leak path, in subject, body and merge messages alike.
        (ON, "Do thing\n\nPaired with claude here.", "claude"),
        (ON, "Repair core, claude-assisted\n", "Banned phrase"),
        (ON, MERGE + "Generated by claude.\n", "Banned phrase"),
        ("enabled = false\n", "mention Booley intentionally", None),
        # [stealth] max_body_lines: opt-in cap on the body, blank and comment lines excluded.
        (CAP_ZERO, "fix(a): do thing\n\nOne line.", "max_body_lines"),
        (CAP_ZERO, "fix(a): do thing\n", None),
        (CAP_ZERO, "fix(a): do thing\n\n\n", None),
        (CAP_ZERO, "fix(a): do thing\n\n# Enter the message\n#\n", None),
        (CAP_ZERO, MERGE + "A long merge narrative.", "max_body_lines"),
        (CAP_ZERO, MERGE + "# Conflicts:\n#\tsrc/thing.sv\n", None),
        (CAP_ZERO, "fix(a): do thing\r\n\r\nBody line.\r\n", "max_body_lines"),
        (ON + "max_body_lines = 2\n", "fix(a): do thing\n\nfirst\n\n\nsecond\n", None),
        (ON + "max_body_lines = 3\n", "fix(a): do thing\n\none\ntwo\nthree\n", None),
        (ON + "max_body_lines = 3\n", "a\n\none\ntwo\nthree\nfour\n", "Body is 4 line(s)"),
    ],
)
def test_validate_message_applies_the_project_stealth_policy(
    tmp_path: Path, stealth: str, message: str, error_fragment: str | None
) -> None:
    errors = validate_message(message, project_root=_write_project(tmp_path, stealth))

    if error_fragment is None:
        assert errors == []
    else:
        assert any(error_fragment in error for error in errors), errors


# ---------------------------------------------------------------------------
# validate_diff over a real staged diff
# ---------------------------------------------------------------------------

LONG_BANNED_LINE = "x" * 40 + " claude " + "y" * 60
STAGED_PREFIX = "Banned phrase '{}' in staged diff: "


@pytest.mark.parametrize(
    ("name", "content", "expected"),
    [
        ("foo.py", "# Normal code addition\nx = 42\n", []),
        (
            "foo.py",
            "# Generated by Claude\n",
            [STAGED_PREFIX.format("claude") + "# Generated by Claude"],
        ),
        # The ``+++ b/claude.py`` header is not scanned, only the added lines.
        ("claude.py", "x = 1\n", []),
        # The same phrase on two lines is reported once.
        (
            "foo.py",
            "# claude wrote this\n" * 2,
            [STAGED_PREFIX.format("claude") + "# claude wrote this"],
        ),
        (
            "foo.py",
            LONG_BANNED_LINE,
            [STAGED_PREFIX.format("claude") + LONG_BANNED_LINE[:77] + "..."],
        ),
        (
            "foo.py",
            "booley_config = BooleyRunner\nmybooleyfile = 1\n",
            [
                STAGED_PREFIX.format("booley") + "booley_config = BooleyRunner",
                STAGED_PREFIX.format("booley") + "mybooleyfile = 1",
            ],
        ),
        ("foo.py", "reagent = precursor\n", []),
        ("generated.txt", "generated docker verification agent\nautomated fix\n", []),
    ],
)
def test_validate_diff_scans_added_lines(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, name: str, content: str, expected: list[str]
) -> None:
    repo = _init_repo(tmp_path, stealth=None)
    _stage(repo, name, content)
    monkeypatch.chdir(repo)

    assert validate_diff(repo) == expected


def test_validate_diff_without_staged_changes_is_clean(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.chdir(_init_repo(tmp_path, stealth=None))

    assert validate_diff() == []


def test_validate_diff_surfaces_git_failure(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """A corrupt index makes git fail; its own stderr is surfaced, not swallowed."""
    repo = _init_repo(tmp_path, stealth=None)
    (repo / ".git" / "index").write_bytes(b"not an index")
    monkeypatch.chdir(repo)

    errors = validate_diff()

    assert len(errors) == 1
    assert "Failed" in errors[0]
    assert "index file" in errors[0]


# ---------------------------------------------------------------------------
# main() entry point in a real repository
# ---------------------------------------------------------------------------

BANNED_STAGED = "# Generated by Claude\n"
OK = "Commit message OK."
SKIPPED = "checks skipped"


def _make_layout(tmp_path: Path, layout: str, stealth: str) -> Path:
    """Build the repository *layout* names and return the directory ``main`` runs in."""
    if layout == "none":
        return _init_repo(tmp_path, stealth=None)
    if layout == "source":
        (tmp_path / "pyproject.toml").write_bytes(b"[tool.booley]\nsource_checkout = true\n")
        return _init_repo(tmp_path, stealth)
    if layout == "state":
        # The Booley Directory's own repository holds booley.toml at its root.
        state = tmp_path / ".booley"
        state.mkdir()
        _run_checked(["git", "init", "-q", str(state)])
        (state / "booley.toml").write_bytes(f"[stealth]\n{stealth}".encode())
        return state
    return _init_repo(tmp_path, stealth)


@pytest.mark.parametrize(
    ("layout", "stealth", "staged", "argv", "returncode", "stderr_fragment"),
    [
        ("project", ON, "", ["Update ALU"], 0, OK),
        ("project", CAP_ZERO, "", ["Update ALU\n\nA body line."], 1, "max_body_lines"),
        ("project", ON, "", ["mention claude"], 1, "Banned phrase"),
        ("project", ON, BANNED_STAGED, ["Update ALU"], 1, "staged diff"),
        ("project", ON, BANNED_STAGED, ["--no-diff", "Update ALU"], 0, OK),
        ("project", "enabled = false\n", BANNED_STAGED, ["mention Booley"], 0, OK),
        ("none", "", "", ["bad claude"], 0, SKIPPED),
        ("source", ON, "", ["docs: explain Booley architecture"], 0, SKIPPED),
        ("state", ON, "", ["mention claude"], 1, "Banned phrase"),
    ],
)
def test_main_validates_only_configured_repositories(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
    layout: str,
    stealth: str,
    staged: str,
    argv: list[str],
    returncode: int,
    stderr_fragment: str,
) -> None:
    repo = _make_layout(tmp_path, layout, stealth)
    if staged:
        _stage(repo, "note.txt", staged)
    monkeypatch.chdir(repo)
    monkeypatch.setattr(sys, "argv", ["validate_commit_msg.py", *argv])

    assert main() == returncode
    assert stderr_fragment in capsys.readouterr().err


