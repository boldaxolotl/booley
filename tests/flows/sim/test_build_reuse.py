def test_closure_may_name_exact_toolchain_files_outside_every_root(tmp_path: Path) -> None:
    project, work, build, identity = _fresh_build(tmp_path)
    real_bin = tmp_path / "usr-local-bin" / "verilator_bin"
    real_bin.parent.mkdir()
    real_bin.write_text("real binary", encoding="utf-8")
    sibling = real_bin.with_name("unrelated")
    sibling.write_text("not hashed by the identity", encoding="utf-8")
    (build / "Vtop__ver.d").write_text(f"Vtop.cpp : {real_bin} src/top.sv\n", encoding="utf-8")
    with pytest.raises(ReadClosureError, match="outside the allowed roots"):
        collect_read_closure(build, work, identity, project, _settled_capture_ns())

    pinned = replace(identity, tool_files=frozenset({real_bin.resolve()}))
    closure = collect_read_closure(build, work, pinned, project, _settled_capture_ns())
    assert closure[f"abs:{real_bin.resolve()}"] == _sha(real_bin)
    assert verify_read_closure(closure, work, pinned, project)
    assert not verify_read_closure(
        {**closure, f"abs:{sibling.resolve()}": _sha(sibling)}, work, pinned, project
    )


