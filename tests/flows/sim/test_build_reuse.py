def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _identity(root: Path, include: Path | None = None) -> VerilatorIdentity:
    verilator_root = root / "vroot"
    (verilator_root / "include").mkdir(parents=True, exist_ok=True)
    verilated_mk = verilator_root / "include" / "verilated.mk"
    if not verilated_mk.exists():
        verilated_mk.write_text("CXX = g++\nLINK = g++\n", encoding="utf-8")
    dirs = (include.resolve(),) if include is not None else ()
    return VerilatorIdentity("tool", verilator_root.resolve(), dirs)


