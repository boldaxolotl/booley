def _stock_recipe(build_root: Path, vc: str, *, make_options: str = "-j4") -> None:
    """Write what the Edalize flow API generates for one Verilator Target."""
    build_root.mkdir(parents=True, exist_ok=True)
    (build_root / "Makefile").write_text(
        "#Auto generated by Edalize\n\n"
        "all: post_build\n\n"
        "pre_build: \n\n"
        "Vtop.mk: demo.vc src/top.sv | pre_build\n"
        "\t$(EDALIZE_LAUNCHER) verilator -f demo.vc\n\n"
        "Vtop: Vtop.mk src/dpi.cpp | pre_build\n"
        f"\t$(EDALIZE_LAUNCHER) make -f Vtop.mk {make_options}\n\n"
        "post_build: Vtop\n\n"
        "pre_run: \n\n"
        "run: pre_run\n\n"
        "post_run: run\n",
        encoding="utf-8",
    )
    (build_root / "demo.vc").write_text(vc, encoding="utf-8")
    (build_root / "src" / "inc").mkdir(parents=True, exist_ok=True)


