def _fresh_build(tmp_path: Path) -> tuple[Path, Path, Path, VerilatorIdentity]:
    """A generation whose depfiles name staged, generated, and toolchain files."""
    project = tmp_path / "project"
    work = project / ".booley_project" / "g" / "0123456789abcdef"
    build = work
    (build / "src").mkdir(parents=True)
    identity = _identity(tmp_path)
    header = identity.verilator_root / "include" / "verilated.h"
    header.write_text("// verilated\n", encoding="utf-8")
    verilator_bin = identity.verilator_root / "bin" / "verilator_bin"
    verilator_bin.parent.mkdir(parents=True, exist_ok=True)
    verilator_bin.write_text("binary", encoding="utf-8")
    (build / "src" / "top.sv").write_text("module top; endmodule\n", encoding="utf-8")
    (build / "src" / "defs.svh").write_text("`define X 1\n", encoding="utf-8")
    (build / "Vtop.cpp").write_text("// generated\n", encoding="utf-8")
    (build / "dpi.cpp").write_text("// dpi\n", encoding="utf-8")
    (build / "Vtop__ver.d").write_text(
        f"Vtop.cpp Vtop.h : {verilator_bin} src/top.sv src/defs.svh\n", encoding="utf-8"
    )
    for stem, source in (("Vtop", "Vtop.cpp"), ("dpi", "dpi.cpp")):
        (build / f"{stem}.o").write_bytes(b"object")
        (build / f"{stem}.d").write_text(f"{stem}.o: {source} {header}\n", encoding="utf-8")
    return project, work, build, identity


def _settled_capture_ns() -> int:
    """A capture time safely after every fixture file's inode change."""
    return time.time_ns() + 10 * build_reuse.RACE_MARGIN_NS


def test_read_closure_classifies_generation_and_toolchain_files(tmp_path: Path) -> None:
    project, work, build, identity = _fresh_build(tmp_path)

    closure = collect_read_closure(build, work, identity, project, _settled_capture_ns())

    root = identity.verilator_root
    assert set(closure) == {
        "work:src/top.sv",
        "work:src/defs.svh",
        "work:Vtop.cpp",
        "work:dpi.cpp",
        f"abs:{root / 'bin' / 'verilator_bin'}",
        f"abs:{root / 'include' / 'verilated.h'}",
    }
    assert closure["work:src/defs.svh"] == _sha(build / "src" / "defs.svh")
    assert verify_read_closure(closure, work, identity, project)


@pytest.mark.parametrize(
    ("victim", "change"),
    [
        ("src/defs.svh", "included header"),
        ("dpi.cpp", "DPI source"),
        ("vroot/include/verilated.h", "toolchain header"),
    ],
)
def test_read_closure_detects_any_changed_file(tmp_path: Path, victim: str, change: str) -> None:
    project, work, build, identity = _fresh_build(tmp_path)
    closure = collect_read_closure(build, work, identity, project, _settled_capture_ns())
    path = tmp_path / victim if victim.startswith("vroot") else build / victim
    path.write_text(f"// {change} edited\n", encoding="utf-8")
    assert not verify_read_closure(closure, work, identity, project)


@pytest.mark.parametrize("case", ["missing-d", "two-ver-d", "no-objects", "outside", "race"])
def test_read_closure_refuses_incomplete_or_unsafe_evidence(tmp_path: Path, case: str) -> None:
    project, work, build, identity = _fresh_build(tmp_path)
    captured = _settled_capture_ns()
    if case == "missing-d":
        (build / "dpi.d").unlink()
    elif case == "two-ver-d":
        (build / "Valt__ver.d").write_text("Valt.cpp : src/top.sv\n", encoding="utf-8")
    elif case == "no-objects":
        for path in build.glob("*.o"):
            path.unlink()
    elif case == "outside":
        stray = tmp_path / "stray.h"
        stray.write_text("// outside every allowed root\n", encoding="utf-8")
        (build / "dpi.d").write_text(f"dpi.o: dpi.cpp {stray}\n", encoding="utf-8")
    else:
        captured = time.time_ns()  # toolchain header changed "during" the build
    with pytest.raises(ReadClosureError):
        collect_read_closure(build, work, identity, project, captured)


@pytest.mark.parametrize(
    "tamper",
    ["escape", "outside-abs", "relative-abs", "unknown-kind", "empty", "not-a-dict", "symlink"],
)
def test_read_closure_verification_rejects_hostile_manifests(tmp_path: Path, tamper: str) -> None:
    project, work, build, identity = _fresh_build(tmp_path)
    closure: Any = collect_read_closure(build, work, identity, project, _settled_capture_ns())
    secret = tmp_path / "secret"
    secret.write_text("secret", encoding="utf-8")
    if tamper == "escape":
        closure["work:../../../../secret"] = _sha(secret)
    elif tamper == "outside-abs":
        closure[f"abs:{secret}"] = _sha(secret)
    elif tamper == "relative-abs":
        closure["abs:secret"] = _sha(secret)
    elif tamper == "unknown-kind":
        closure["file:secret"] = _sha(secret)
    elif tamper == "empty":
        closure = {}
    elif tamper == "not-a-dict":
        closure = list(closure)
    else:
        target = build / "src" / "top.sv"
        moved = build / "top.real"
        target.rename(moved)
        target.symlink_to(moved)
    assert not verify_read_closure(closure, work, identity, project)


