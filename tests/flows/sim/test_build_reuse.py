def _fake_install(tmp_path: Path) -> tuple[Path, dict[str, str]]:
    """A Verilator wrapper, install tree, and scripted C++ driver."""
    root = tmp_path / "vroot"
    bin_dir = tmp_path / "bin"
    include = tmp_path / "sysinclude"
    for path in (root / "bin", root / "include", bin_dir, include / "bits"):
        path.mkdir(parents=True)
    (include / "stdio.h").write_text("// libc\n", encoding="utf-8")
    (root / "include" / "verilated.mk").write_text(
        "CXX = fakecxx\nLINK = fakecxx\nAR = ar\n", encoding="utf-8"
    )
    (root / "include" / "verilated.h").write_text("// v\n", encoding="utf-8")
    (root / "bin" / "verilator_bin").write_text("bin\n", encoding="utf-8")
    scripts = {
        "verilator": f"print({str(root)!r})\n",
        "fakecxx": (
            "import sys\n"
            "args = sys.argv[1:]\n"
            "if args and args[0].startswith('-print-prog-name='):\n"
            "    print(sys.argv[0])\n"
            "elif args and args[0].startswith('-print-file-name='):\n"
            "    import os\n"
            "    name = args[0].split('=', 1)[1]\n"
            f"    found = os.path.join({str(tmp_path / 'syslib')!r}, name)\n"
            "    print(found if os.path.isfile(found) else name)\n"
            "elif '-E' in args:\n"
            "    sys.stderr.write('#include <...> search starts here:\\n "
            f"{include}\\nEnd of search list.\\n')\n"
            "else:\n"
            "    print('fakecxx 1.0 ' + ' '.join(args))\n"
        ),
    }
    for name, body in scripts.items():
        script = bin_dir / name
        script.write_text(f"#!{sys.executable}\n{body}", encoding="utf-8")
        script.chmod(0o755)
    return root, {"PATH": f"{bin_dir}{os.pathsep}{os.environ['PATH']}"}


@posix_only
def test_toolchain_identity_covers_install_compiler_and_system_headers(tmp_path: Path) -> None:
    root, environment = _fake_install(tmp_path)
    identity = verilator_identity(environment)
    assert identity is not None
    assert identity.verilator_root == root.resolve()
    assert identity.system_include_dirs == ((tmp_path / "sysinclude").resolve(),)
    assert verilator_identity(environment) == identity

    # Only the compiler drivers are mandatory, but any named tool must resolve.
    mk = root / "include" / "verilated.mk"
    mk.write_text("CXX = fakecxx\nLINK = fakecxx\n", encoding="utf-8")
    assert verilator_identity(environment) is not None
    mk.write_text("CXX = fakecxx\nLINK = fakecxx\nAR = no-such-ar\n", encoding="utf-8")
    assert verilator_identity(environment) is None
    mk.write_text("CXX = fakecxx\nLINK = fakecxx\n", encoding="utf-8")

    for change in (
        lambda: (root / "include" / "verilated.h").write_text("// v2\n", encoding="utf-8"),
        lambda: (tmp_path / "sysinclude" / "bits" / "new.h").write_text("", encoding="utf-8"),
        lambda: (tmp_path / "bin" / "fakecxx").write_text(
            (tmp_path / "bin" / "fakecxx").read_text(encoding="utf-8") + "# v2\n",
            encoding="utf-8",
        ),
    ):
        before = verilator_identity(environment)
        change()
        after = verilator_identity(environment)
        assert before is not None and after is not None
        assert after.digest != before.digest


@posix_only
def test_toolchain_identity_hashes_linked_system_libraries(tmp_path: Path) -> None:
    _root, environment = _fake_install(tmp_path)
    syslib = tmp_path / "syslib"
    syslib.mkdir()
    (syslib / "libz.a").write_bytes(b"archive v1")
    libz = (("libz.so", "libz.a"),)
    before = verilator_identity(environment, libz)
    assert before is not None
    assert (syslib / "libz.a").resolve() in before.tool_files
    assert verilator_identity(environment) != before
    (syslib / "libz.a").write_bytes(b"archive v2")
    after = verilator_identity(environment, libz)
    assert after is not None and after.digest != before.digest
    # A library the linker cannot be shown to find is never guessed at.
    assert verilator_identity(environment, (("libnone.so", "libnone.a"),)) is None


