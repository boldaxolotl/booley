def _edam(work: Path, cores: dict[str, Path]) -> Path:
    work.mkdir(parents=True, exist_ok=True)
    edam = work / "demo.eda.yml"
    edam.write_text(
        json.dumps(
            {
                "cores": {
                    name: {"core_file": os.path.relpath(path, work), "dependencies": []}
                    for name, path in cores.items()
                }
            }
        ),
        encoding="utf-8",
    )
    return edam


def test_core_closure_hashes_every_dependency_core(tmp_path: Path) -> None:
    project = tmp_path / "project"
    (project / "rtl").mkdir(parents=True)
    adapter = project / "adapter.core"
    rtl = project / "rtl" / "rtl.core"
    adapter.write_text("CAPI=2:\nname: a:b:adapter:1\n", encoding="utf-8")
    rtl.write_text("CAPI=2:\nname: a:b:rtl:1\n", encoding="utf-8")
    edam = _edam(project / ".booley_project" / "g", {"a:b:adapter:1": adapter, "a:b:rtl:1": rtl})

    closure = capture_core_closure(edam, project)

    assert closure == {
        "a:b:adapter:1": f"adapter.core:{_sha(adapter)}",
        "a:b:rtl:1": f"rtl/rtl.core:{_sha(rtl)}",
    }
    rtl.write_text("CAPI=2:\nname: a:b:rtl:1\ndescription: edited\n", encoding="utf-8")
    assert capture_core_closure(edam, project) != closure


