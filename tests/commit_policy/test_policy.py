class TestStealthEnabled:
    """[stealth] enabled is opt-out — default True, gates hook + prompt note."""

    def _project(self, tmp_path, toml_body: bytes | None):
        bp = tmp_path / ".booley_project"
        bp.mkdir(parents=True)
