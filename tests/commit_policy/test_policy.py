class TestBuildBannedRes:
    def test_returns_compiled_patterns(self):
        result = _build_banned_res(["claude", "openai"])
        assert len(result) == 2
        for _phrase, pattern in result:
            assert isinstance(pattern, re.Pattern)

    def test_empty_list(self):
        assert _build_banned_res([]) == []

    def test_patterns_are_case_insensitive(self):
        result = _build_banned_res(["claude"])
        _, pattern = result[0]
        assert pattern.search("Claude is here")
        assert pattern.search("CLAUDE")
        assert pattern.search("claude")

    def test_word_boundary_matching(self):
        result = _build_banned_res(["agent"])
        _, pattern = result[0]
        assert pattern.search("the agent did it")
        # "reagent" contains "agent" but not at a word boundary — or does it?
        # \b matches between 'e' and 'a' only if class transitions. "reagent"
        # has no transition before "agent" in the middle. Actually \bagent\b
        # would NOT match inside "reagent" because there's no boundary.
        assert not pattern.search("reagent")

    def test_special_regex_chars_escaped(self):
        """Phrases with regex metacharacters should be escaped."""
        result = _build_banned_res(["auto-review"])
        _, pattern = result[0]
        assert pattern.search("this is auto-review stuff")
        # The hyphen should be literal, not a range
        assert not pattern.search("autoreview")


