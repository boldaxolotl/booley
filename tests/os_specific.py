_REGISTERED = frozenset(OS_SPECIFIC_TESTS)


def is_os_specific(relative_path: str) -> bool:
    """True when the repository-relative test module is registered as OS-specific."""
    return relative_path in _REGISTERED


def pytest_collection_modifyitems(config: pytest.Config, items: list[pytest.Item]) -> None:
    """Mark the tests of registered modules."""
    root = config.rootpath.resolve()
    for item in items:
        if is_os_specific(item.path.resolve().relative_to(root).as_posix()):
            item.add_marker(pytest.mark.os_specific)
