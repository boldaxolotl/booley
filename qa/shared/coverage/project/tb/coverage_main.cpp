static void native_fault(const std::string& test) {
    const char* name = std::getenv("BOOLEY_COVERAGE_FILE");
    if (!name || test.rfind("native-", 0) != 0) return;
    if (test == "native-missing") { std::remove(name); return; }
    if (test == "native-stale") { struct utimbuf old = {1,1}; utime(name, &old); return; }
    if (test == "native-malformed" || test == "native-incompatible") {
        std::ofstream out(name);
        out << (test == "native-incompatible" ? "# SystemC::Coverage-999\n" : "# SystemC::Coverage-3\ninvalid record\n");
        return;
    }
    std::ifstream input(name);
    std::string line;
    while (std::getline(input,line)) {
        if (line.rfind("C '",0) != 0) continue;
        if (test == "native-generated" || test == "native-foreign") {
            const std::string source = test == "native-generated"
                ? "qa-generated/coverage_helper.sv" : "foreign/coverage_library.sv";
            if (test == "native-generated") {
                std::filesystem::create_directory("qa-generated");
                std::ofstream generated(source);
                generated << "// Generated by the owned QA native boundary\nmodule coverage_helper; endmodule\n";
            }
            auto field = line.find("\x01" "f" "\x02");
            auto end = line.find('\x01', field+3);
            if (field == std::string::npos || end == std::string::npos) std::exit(2);
            line.replace(field+3, end-field-3, source);
            std::ofstream out(name,std::ios::app); out << line << '\n';
            std::cout << "QA_NATIVE_ORIGIN " << source << '\n';
            return;
        }
        auto start = line.find("\x01t\x02");
        auto end = line.find('\x01', start+3);
        if (start == std::string::npos || end == std::string::npos) continue;
        line.replace(start+3,end-start-3,test.substr(7));
        std::ofstream out(name,std::ios::app); out << line << '\n';
        return;
    }
}
int main(int argc, char** argv) {
    VerilatedContext context; context.commandArgs(argc, argv);
    Vcoverage_dut dut{&context};
    std::string test = "gap";
    for (int i=1; i<argc; ++i) {
        std::string arg = argv[i];
        if (arg.rfind("+test=", 0) == 0) test = arg.substr(6);
    }
    dut.clk=0; dut.reset=1; dut.choice=0; dut.eval();
    dut.clk=1; dut.eval(); dut.clk=0; dut.reset=0; dut.eval();
#if VM_COVERAGE
    if (test == "out-of-order") booley_coverage_write();
    if (test != "missing-start") booley_coverage_start();
    if (test == "duplicate-start") booley_coverage_start();
#endif
    for (int i=0; i<18; ++i) {
        dut.clk=0; dut.choice=i % (test == "full" ? 3 : 2); dut.eval();
        dut.clk=1; dut.eval();
        if (dut.decoded != (1 << dut.choice)) return 1;
    }
#if VM_COVERAGE
    if (test == "failed-hook") {
        const char* path = std::getenv("BOOLEY_COVERAGE_FILE");
        if (!path || geteuid() == 0) { std::cerr << "Non-root owned write-fault runtime required\n"; return 2; }
        int fd = open(path, O_CREAT | O_EXCL | O_WRONLY | O_NOFOLLOW, 0400);
        if (fd < 0) { std::perror("QA write-fault setup"); return 2; }
        close(fd);
        std::cout << "QA_WRITE_PROTECTED " << path << std::endl;
    }
    if (test != "missing-write") booley_coverage_write();
    if (test == "duplicate-write") booley_coverage_write();
    native_fault(test);
#endif
    dut.final();
    bool failed = test == "fail";
    std::cout << (failed ? "[SIM_RESULT] FAILED\n" : "[SIM_RESULT] PASSED\n");
    return failed ? 1 : 0;
}
