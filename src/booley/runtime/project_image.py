"""Build a project sandbox image that bakes the repo's Python deps (ADR 0018).

The base ``booley-sandbox`` image is project-agnostic and never installs a
project's ``requirements.txt`` — and the sandbox's runtime egress is locked to
LLM endpoints, so ``pip install`` cannot run at MCP endpoint runtime. ``booley init`` bridges
this: it bakes exactly the requirements files a project lists in
``[sandbox].pip_requirements`` — nothing is auto-discovered. It drops pins on
Booley-:data:`MANAGED_PACKAGES` so a design repo can't downgrade the driver,
skips non-bakeable lines (editable/``-r``/``file:``), consolidates the rest,
generates an untracked ``.booley_project/docker/{requirements.txt,Dockerfile}``
extending ``booley-sandbox``, and builds the automatically selected
``<slug>-booley-sandbox`` image.

Notes:
  - No ``[sandbox].pip_requirements`` (or an empty list) means nothing is baked
    — the project runs the base image.
  - An explicit ``[sandbox].image`` other than the generated name means the user
    manages their own image; auto-generation is skipped.
"""

from __future__ import annotations

import hashlib
import logging
import re
import subprocess
from pathlib import Path

from booley.runtime.image_provenance import (
    LABEL_BUILD_ORIGIN,
    LABEL_PARENT_ARTIFACT,
    LABEL_PARENT_ARTIFACT_KIND,
    LABEL_RECIPE_FINGERPRINT,
    PARENT_ARTIFACT_LOCAL_IMAGE_ID,
    resolve_build_context_fingerprint,
)

logger = logging.getLogger(__name__)

BASE_IMAGE = "booley-sandbox"

# Packages the base sandbox image pins and manages (ADR 0019). A project
# requirements pin on any of these shadows the image's version at build time
# (Ibex's ``fusesoc==2.4.3`` silently downgraded the managed 2.4.6, breaking the
# driver), so such pins are dropped-and-warned rather than baked (SETUP-5).
# Both distribution names are guarded: "booley-rtl" is the PyPI name; plain
# "booley" catches stale pins written before the rename.
MANAGED_PACKAGES = frozenset({"fusesoc", "edalize", "booley", "booley-rtl"})

_GENERATED_HEADER = "# AUTO-GENERATED by `booley init` (ADR 0018)."

# Any file carrying this directive is treated as user-owned even if it still
# begins with the generated header — an explicit "hands off" for edits init's
# header-check can't otherwise see (SETUP-6).
_KEEP_DIRECTIVE = "# booley:keep"

# Trailing self-hash line write_project_image_files() stamps on generated
# files. It is how re-init tells "stale generated file" (hash matches —
# regenerate) from "hand-edited generated file" (hash mismatch — user-owned),
# closing the SETUP-6 hole where an edit that kept the header was clobbered.
_CONTENT_HASH_PREFIX = "# booley:content-hash="

_FROM_RE = re.compile(
    r"^\s*FROM(?:\s+--platform=\S+)?\s+(?P<image>[^\s]+)",
    re.IGNORECASE | re.MULTILINE,
)
_PARENT_DIRECTIVE_RE = re.compile(r"^\s*#\s*booley:parent=(?P<image>\S+)\s*$", re.MULTILINE)


class DockerImageError(RuntimeError):
    """Docker could not authoritatively inspect a Session Image."""


def _content_digest(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]


def _stamp_content_hash(body: str) -> str:
    """Append the self-hash line that lets re-init detect hand edits."""
    if body and not body.endswith("\n"):
        body += "\n"
    return f"{body}{_CONTENT_HASH_PREFIX}{_content_digest(body)}\n"


def _matches_content_hash(text: str) -> bool:
    """True when *text* is byte-for-byte what init last wrote.

    Files written before hashing carry no hash line and stay managed (the
    legacy behavior — regenerated on re-init). With a hash line present, ANY
    hand edit — even one that keeps the generated header — flips the file to
    user-owned.
    """
    lines = text.splitlines(keepends=True)
    for i in range(len(lines) - 1, -1, -1):
        if lines[i].startswith(_CONTENT_HASH_PREFIX):
            declared = lines[i][len(_CONTENT_HASH_PREFIX) :].strip()
            rest = "".join(lines[:i] + lines[i + 1 :])
            return declared == _content_digest(rest)
    return True


def project_image_name(project_root: Path) -> str:
    """Deterministic tag for the generated project image (docker-name-safe)."""
    slug = re.sub(r"[^a-z0-9_.-]+", "-", project_root.name.lower()).strip("-._")
    return f"{slug or 'project'}-{BASE_IMAGE}"


def dockerfile_parent_image(dockerfile: Path) -> str | None:
    """Return an unambiguous direct parent, or ``None`` for a complex recipe."""
    try:
        text = dockerfile.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return None
    directive = _PARENT_DIRECTIVE_RE.search(text)
    if directive is not None:
        return directive.group("image")
    matches = list(_FROM_RE.finditer(text))
    if len(matches) != 1:
        return None
    image = matches[0].group("image")
    if image.startswith("$"):
        return None
    return image


