def resolve_requirements(
    project_root: Path,
    pip_requirements: list[str] | None,
) -> tuple[list[Path], list[str]]:
    """Resolve the requirements files listed in ``[sandbox].pip_requirements``.

    There is no auto-discovery: only the files a project names are baked. An
    empty or absent list bakes nothing. Returns ``(existing_paths,
    missing_entries)``; entries are repo-root-relative.
    """
    if not pip_requirements:
        return [], []
    existing: list[Path] = []
    missing: list[str] = []
    for entry in pip_requirements:
        p = project_root / entry
        if p.is_file():
            existing.append(p)
        else:
            missing.append(entry)
    return existing, missing


