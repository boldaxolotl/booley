def build_project_image(image: str, docker_dir: Path, *, verbose: bool = False) -> bool:
    """``docker build`` the generated image. Context is *docker_dir* (small, no
    repo .dockerignore interference). Returns success."""
    dockerfile = docker_dir / "Dockerfile"
    if not dockerfile.is_file():
        logger.error("project image Dockerfile not found at %s", dockerfile)
        return False
    labels = [
        "--label",
        f"{LABEL_RECIPE_FINGERPRINT}={resolve_build_context_fingerprint(docker_dir)}",
        "--label",
        f"{LABEL_BUILD_ORIGIN}=local",
    ]
    parent = dockerfile_parent_image(dockerfile)
    try:
        parent_id = docker_image_id(parent) if parent else None
    except DockerImageError as exc:
        logger.error("project image parent inspection failed: %s", exc)
        return False
    if parent_id:
        labels += [
            "--label",
            f"{LABEL_PARENT_ARTIFACT_KIND}={PARENT_ARTIFACT_LOCAL_IMAGE_ID}",
            "--label",
            f"{LABEL_PARENT_ARTIFACT}={parent_id}",
        ]
    cmd = ["docker", "build", "-t", image, *labels, "-f", str(dockerfile), str(docker_dir)]
    try:
        result = subprocess.run(
            cmd,
            capture_output=not verbose,
            text=True,
            timeout=1800,
            check=False,
        )
    except (FileNotFoundError, subprocess.SubprocessError) as exc:
        logger.error("project image build failed: %s", exc)
        return False
    if result.returncode != 0:
        detail = (getattr(result, "stderr", "") or "").strip()
        logger.error("project image build failed (rc=%s): %s", result.returncode, detail[-500:])
        return False
    return True


def docker_image_id(image: str) -> str | None:
    """Resolve a local Docker artifact; return ``None`` only when it is absent."""
    try:
        result = subprocess.run(
            ["docker", "image", "inspect", image, "--format", "{{.Id}}"],
            capture_output=True,
            text=True,
            timeout=30,
            check=False,
        )
    except (FileNotFoundError, subprocess.SubprocessError) as exc:
        raise DockerImageError(f"could not inspect Docker image {image!r}: {exc}") from exc
    value = result.stdout.strip()
    if result.returncode == 0:
        if value:
            return value
        raise DockerImageError(f"Docker returned no immutable ID for image {image!r}")
    detail = (result.stderr or result.stdout).strip()
    if "no such image" in detail.lower():
        return None
    raise DockerImageError(
        f"could not inspect Docker image {image!r}: {detail or f'Docker exited {result.returncode}'}"
    )
